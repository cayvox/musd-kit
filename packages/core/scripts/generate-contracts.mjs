// Codegen: derive the MUSD address maps + `as const` ABIs for the dev-facing
// contract set DIRECTLY from the official `@mezo-org/musd-contracts` hardhat-deploy
// artifacts (decision O10). Nothing here is hand-transcribed, re-run
// `pnpm --filter @musd-kit/core generate` after bumping the package.
//
// Output (committed):
//   src/_generated/addresses.ts, DEPLOYMENTS[chainId][contract] = Address
//   src/_generated/abis.ts, <contract>Abi = [...] as const
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)
const pkgJsonPath = require.resolve('@mezo-org/musd-contracts/package.json')
const pkgRoot = dirname(pkgJsonPath)
const pkgVersion = JSON.parse(readFileSync(pkgJsonPath, 'utf8')).version
const deployments = join(pkgRoot, 'deployments')

// hardhat-deploy network dir → EVM chainId (verified: deployments/<net>/.chainId)
const NETWORKS = [
  { dir: 'matsnet', chainId: 31611 },
  { dir: 'mainnet', chainId: 31612 },
]

// hardhat-deploy artifact name → SDK key. The dev-facing subset only
// (`docs/01-ground-truth.md` §4 / §5); pools + PCV stay protocol-internal.
const CONTRACTS = {
  borrowerOperations: 'BorrowerOperations',
  troveManager: 'TroveManager',
  sortedTroves: 'SortedTroves',
  hintHelpers: 'HintHelpers',
  priceFeed: 'PriceFeed',
  interestRateManager: 'InterestRateManager',
  musd: 'MUSD',
}

function loadArtifact(net, artifact) {
  const p = join(deployments, net, `${artifact}.json`)
  return JSON.parse(readFileSync(p, 'utf8'))
}

// Sanity: the artifact's .chainId file must match what we expect.
for (const { dir, chainId } of NETWORKS) {
  const onDisk = readFileSync(join(deployments, dir, '.chainId'), 'utf8').trim()
  if (Number(onDisk) !== chainId) {
    throw new Error(`chainId mismatch for ${dir}: artifact says ${onDisk}, expected ${chainId}`)
  }
}

// --- addresses ---
const addrLines = []
for (const { dir, chainId } of NETWORKS) {
  const entries = Object.entries(CONTRACTS)
    .map(([key, artifact]) => `    ${key}: '${loadArtifact(dir, artifact).address}',`)
    .join('\n')
  addrLines.push(`  ${chainId}: {\n${entries}\n  },`)
}

const addressesTs = `// GENERATED by scripts/generate-contracts.mjs from @mezo-org/musd-contracts@${pkgVersion}.
// Do not edit by hand. Cross-checked against docs/01-ground-truth.md §4 in tests.
import type { Address } from 'viem'

export const SOURCE_PACKAGE_VERSION = '${pkgVersion}' as const

export const DEPLOYMENTS = {
${addrLines.join('\n')}
} as const satisfies Record<number, Record<string, Address>>
`

// --- abis ---
const abiChunks = [
  `// GENERATED by scripts/generate-contracts.mjs from @mezo-org/musd-contracts@${pkgVersion}.`,
  '// Do not edit by hand. Full on-chain ABIs (functions, events, errors) kept as-is',
  '// for type inference and Phase-7 revert decoding.',
  '',
]
for (const [key, artifact] of Object.entries(CONTRACTS)) {
  // ABI is identical across networks for the same contract; take matsnet.
  const { abi } = loadArtifact('matsnet', artifact)
  abiChunks.push(`export const ${key}Abi = ${JSON.stringify(abi)} as const\n`)
}

const outDir = join(dirname(new URL(import.meta.url).pathname), '..', 'src', '_generated')
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'addresses.ts'), addressesTs)
writeFileSync(join(outDir, 'abis.ts'), abiChunks.join('\n'))

console.log(
  `generated src/_generated/{addresses,abis}.ts from @mezo-org/musd-contracts@${pkgVersion}`,
)
